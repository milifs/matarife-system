-- v19 — Módulo Proveedores: compra de animales vivos (Cargas) y pagos
--
-- Reemplaza el Excel "Proveedores-Pagos": una fila de `cargas` = una hoja
-- del Excel (el bloque Faena), y las filas de `carga_pagos` = el bloque PAGOS.
--
-- Esto NO toca el circuito de clientes (remitos/NDP/pagos). Son las compras
-- que Joaco le hace a los proveedores que le venden el animal vivo.
--
-- El SALDO A FAVOR no se guarda: se encadena por proveedor y se recalcula
-- solo (saldo anterior + pagos - total a pagar). Si se corrige una carga
-- vieja, todas las posteriores de ese proveedor se reacomodan sin tocar nada.

-- ═══════════════════════════════════════════
-- 1. PROVEEDORES
-- ═══════════════════════════════════════════
-- Los tres valores numéricos son el DEFAULT del proveedor: se precargan al
-- abrir una carga nueva pero quedan editables carga por carga, porque el
-- precio del kg vivo cambia seguido.
CREATE TABLE IF NOT EXISTS proveedores (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  nombre TEXT NOT NULL,
  -- Desvaste: % que se le descuenta al peso vivo (5 => se paga el 95%)
  desvaste_porcentaje NUMERIC(5,2) NOT NULL DEFAULT 5,
  precio_kg_vivo NUMERIC(12,2) NOT NULL DEFAULT 0,
  -- Rinde que el proveedor asegura (58%). Se usa para la diferencia de rinde.
  rinde_asegurado NUMERIC(5,2) NOT NULL DEFAULT 58,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE proveedores DISABLE ROW LEVEL SECURITY;

-- ═══════════════════════════════════════════
-- 2. CARGAS (una compra a un proveedor)
-- ═══════════════════════════════════════════
-- Puede haber varias cargas en la misma semana y de distintos proveedores.
-- `numero` lo asigna la secuencia de Postgres (PP-0001), no el cliente:
-- así no hay carrera como en remitos/pagos, que hacen max+1 del lado de la app.
CREATE TABLE IF NOT EXISTS cargas (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  numero INT GENERATED BY DEFAULT AS IDENTITY,
  proveedor_id UUID NOT NULL REFERENCES proveedores(id),
  fecha DATE NOT NULL DEFAULT CURRENT_DATE,
  cantidad_animales INT NOT NULL DEFAULT 0,
  kg_vivo NUMERIC(12,2) NOT NULL DEFAULT 0,
  -- Copia del valor del proveedor al momento de la carga (editable)
  desvaste_porcentaje NUMERIC(5,2) NOT NULL DEFAULT 5,
  precio_kg_vivo NUMERIC(12,2) NOT NULL DEFAULT 0,
  rinde_asegurado NUMERIC(5,2) NOT NULL DEFAULT 58,
  -- Se completa DESPUÉS de la faena. Hasta entonces queda NULL y el rinde
  -- no se puede calcular, pero el total a pagar ya está definido.
  kg_media_res NUMERIC(12,2),
  observacion TEXT DEFAULT '',
  registrado_por TEXT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),

  -- ── Columnas calculadas por Postgres ──
  -- Viven acá y no en Dart para que no se puedan desincronizar ni tipear mal.
  -- Ojo: una columna generada no puede referenciar a otra generada, por eso
  -- la cuenta del kg neto aparece repetida en las tres.
  kg_neto NUMERIC(14,4) GENERATED ALWAYS AS (
    kg_vivo * (100 - desvaste_porcentaje) / 100
  ) STORED,
  total_a_pagar NUMERIC(16,2) GENERATED ALWAYS AS (
    ROUND(kg_vivo * (100 - desvaste_porcentaje) / 100 * precio_kg_vivo, 2)
  ) STORED,
  rinde_carga NUMERIC(6,2) GENERATED ALWAYS AS (
    ROUND(
      kg_media_res * 100
        / NULLIF(kg_vivo * (100 - desvaste_porcentaje) / 100, 0),
      2
    )
  ) STORED
);

CREATE INDEX IF NOT EXISTS idx_cargas_proveedor ON cargas (proveedor_id);
CREATE INDEX IF NOT EXISTS idx_cargas_fecha ON cargas (fecha DESC);

ALTER TABLE cargas DISABLE ROW LEVEL SECURITY;

-- ═══════════════════════════════════════════
-- 3. PAGOS DE LA CARGA
-- ═══════════════════════════════════════════
CREATE TABLE IF NOT EXISTS carga_pagos (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  carga_id UUID NOT NULL REFERENCES cargas(id) ON DELETE CASCADE,
  fecha DATE NOT NULL DEFAULT CURRENT_DATE,
  medio TEXT NOT NULL CHECK (medio IN ('efectivo', 'transferencia', 'cheque')),
  monto NUMERIC(16,2) NOT NULL,
  registrado_por TEXT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_carga_pagos_carga ON carga_pagos (carga_id);

ALTER TABLE carga_pagos DISABLE ROW LEVEL SECURITY;

-- ═══════════════════════════════════════════
-- 4. AUDITORÍA DE ELIMINADOS
-- ═══════════════════════════════════════════
-- Mismo criterio que pagos_eliminados/remitos_eliminados: nada se borra sin
-- dejar rastro, y acá la observación es OBLIGATORIA (hay plata de por medio).
CREATE TABLE IF NOT EXISTS cargas_eliminadas (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  carga_id UUID,
  numero INT,
  proveedor_id UUID,
  proveedor_nombre TEXT,
  fecha DATE,
  cantidad_animales INT,
  kg_vivo NUMERIC(12,2),
  kg_media_res NUMERIC(12,2),
  total_a_pagar NUMERIC(16,2),
  total_pagado NUMERIC(16,2),
  -- Los pagos que colgaban de la carga, congelados tal como estaban
  pagos JSONB,
  observacion TEXT NOT NULL,
  eliminado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  eliminado_por TEXT
);

ALTER TABLE cargas_eliminadas DISABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS carga_pagos_eliminados (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  pago_id UUID,
  carga_id UUID,
  carga_numero INT,
  proveedor_nombre TEXT,
  fecha DATE,
  medio TEXT,
  monto NUMERIC(16,2),
  observacion TEXT NOT NULL,
  eliminado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  eliminado_por TEXT
);

ALTER TABLE carga_pagos_eliminados DISABLE ROW LEVEL SECURITY;

