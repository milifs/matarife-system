-- v19.5 — Módulo Depósito: control de stock de medias reses
--
-- PARA QUÉ EXISTE
-- Desde el depósito sacaron dos medias para un cliente y la cajera se olvidó
-- de cargar el remito. Nadie podía decir dónde estaban esas dos medias: plata
-- perdida. Este módulo cierra la ecuación entre lo que se compró, lo que se
-- distribuyó a clientes y lo que quedó guardado en la cámara.
--
-- LA ECUACIÓN (se recalcula sola, NUNCA se guarda, igual que el saldo
-- arrastrado del proveedor):
--
--   stock teórico = medias iniciales
--                 + medias compradas      (cargas × 2 animales)
--                 + entradas manuales     (devoluciones, ajustes)
--                 - medias remitidas      (remitos CONFIRMADOS, por equivalencia)
--                 - salidas pendientes    (salieron sin remito todavía)
--                 - salidas definitivas   (merma, consumo propio: nunca van a tener remito)
--
--   diferencia = stock teórico - último recuento
--
--   diferencia > 0  =>  faltan medias en la cámara: salieron sin registrar
--   diferencia < 0  =>  hay medias de más que el sistema no conoce
--   diferencia = 0  =>  los números dan redondos
--
-- Nada de esto se persiste: se deriva de cargas + remitos + movimientos. Así,
-- corregir un remito viejo o cargar uno atrasado reacomoda todo solo.
--
-- DOS STOCKS SEPARADOS: novillo y cerdo se cuentan aparte (igual que la Lista
-- de reparto, que ya separa CARNE / CERDO). Una media de cerdo no puede tapar
-- un faltante de novillo.

-- ═══════════════════════════════════════════
-- 1. CONFIGURACIÓN DEL ARRANQUE
-- ═══════════════════════════════════════════
-- El sistema tiene remitos de hace meses pero cargas de proveedores recién
-- desde el 20/10/2026, así que contar "desde siempre" daría cualquier cosa.
-- Por eso el depósito arranca de cero en una fecha elegida: se cuenta a mano
-- lo que hay hoy en la cámara y de ahí en adelante manda la ecuación.
--
-- Una sola fila, garantizado por el truco de la columna `unica`: es UNIQUE y
-- el CHECK la obliga a ser TRUE, así que un segundo INSERT rebota.
CREATE TABLE IF NOT EXISTS deposito_config (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  unica BOOLEAN NOT NULL DEFAULT TRUE UNIQUE CHECK (unica),
  -- Desde acá se empiezan a contar cargas y remitos. Lo anterior no se audita.
  fecha_inicio DATE NOT NULL DEFAULT CURRENT_DATE,
  -- Lo que había en la cámara el día del arranque, contado a mano
  medias_novillo NUMERIC(12,4) NOT NULL DEFAULT 0,
  medias_cerdo NUMERIC(12,4) NOT NULL DEFAULT 0,
  registrado_por TEXT,
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE deposito_config DISABLE ROW LEVEL SECURITY;

-- ═══════════════════════════════════════════
-- 2. MOVIMIENTOS DE DEPÓSITO
-- ═══════════════════════════════════════════
-- Las tres clases son cosas distintas, no variantes de lo mismo:
--
-- `entrada`   medias que entran al depósito SIN venir de una carga: una
--             devolución de un cliente o un ajuste a favor. La carga del
--             proveedor NO necesita una entrada: ya suma sola por la ecuación.
--
-- `salida`    medias que salieron de la cámara. Es el botón que aprieta la
--             cajera cuando saca carne y todavía no cargó el remito.
--             Con `espera_remito = TRUE` la salida queda PENDIENTE y se cierra
--             sola por FIFO cuando se carga un remito de ese tipo (la salida
--             más vieja primero). Con FALSE es definitiva: merma, consumo
--             propio o rotura, nunca va a tener un remito que la respalde.
--
-- `recuento`  no mueve nada. Es la foto de lo que se contó físicamente en la
--             cámara, para comparar contra el stock teórico. El último
--             recuento de cada tipo es el que manda.
--
-- `medias` va SIEMPRE en positivo: el signo lo pone la clase.
CREATE TABLE IF NOT EXISTS deposito_movimientos (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Lo asigna la secuencia de Postgres (D-0001), no la app: así no hay carrera
  -- como en remitos/pagos, que hacen max+1 del lado del cliente.
  numero INT GENERATED BY DEFAULT AS IDENTITY,
  tipo TEXT NOT NULL CHECK (tipo IN ('novillo', 'cerdo')),
  clase TEXT NOT NULL CHECK (clase IN ('entrada', 'salida', 'recuento')),
  medias NUMERIC(12,4) NOT NULL DEFAULT 0 CHECK (medias >= 0),
  -- Solo tiene sentido en las salidas; en entradas y recuentos se ignora.
  espera_remito BOOLEAN NOT NULL DEFAULT TRUE,
  fecha DATE NOT NULL DEFAULT CURRENT_DATE,
  observacion TEXT DEFAULT '',
  registrado_por TEXT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- El FIFO de las salidas pendientes ordena por `creado_en`, no por `fecha`:
-- lo que importa es en qué orden se cargaron las cosas en el sistema.
CREATE INDEX IF NOT EXISTS idx_deposito_mov_creado
  ON deposito_movimientos (creado_en DESC);
CREATE INDEX IF NOT EXISTS idx_deposito_mov_tipo_clase
  ON deposito_movimientos (tipo, clase);

ALTER TABLE deposito_movimientos DISABLE ROW LEVEL SECURITY;

-- ═══════════════════════════════════════════
-- 3. AUDITORÍA DE BAJAS
-- ═══════════════════════════════════════════
-- Misma regla que en proveedores: la cajera puede borrar lo que cargó mal,
-- pero `observacion` es OBLIGATORIA. Un movimiento borrado sin motivo sería
-- justamente el agujero que este módulo vino a tapar.
CREATE TABLE IF NOT EXISTS deposito_movimientos_eliminados (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  movimiento_id UUID,
  movimiento_numero INT,
  tipo TEXT,
  clase TEXT,
  medias NUMERIC(12,4),
  espera_remito BOOLEAN,
  fecha DATE,
  observacion_original TEXT,
  observacion TEXT NOT NULL,
  eliminado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  eliminado_por TEXT
);

ALTER TABLE deposito_movimientos_eliminados DISABLE ROW LEVEL SECURITY;

