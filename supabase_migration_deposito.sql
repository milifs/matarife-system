SELECT r.id, 'gestionar_deposito' FROM roles r WHERE r.es_admin = TRUE
ON CONFLICT DO NOTHING;

-- Y también los roles que ya manejan proveedores: es la misma persona (la
-- cajera carga la compra y es la que saca la carne de la cámara).
INSERT INTO rol_permisos (rol_id, permiso_id)
SELECT rp.rol_id, 'gestionar_deposito' FROM rol_permisos rp
WHERE rp.permiso_id = 'gestionar_proveedores'
ON CONFLICT DO NOTHING;
